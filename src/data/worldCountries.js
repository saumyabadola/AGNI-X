// Helper to look up a country by code or name
export function getCountryByCode(code) {
  if (!code) return null;
  return worldCountries.find((c) => c.code.toUpperCase() === code.toUpperCase()) || null;
}

// Helper to find countries matching search query
export function searchCountries(query) {
  if (!query || query.trim() === "") return worldCountries;
  const q = query.toLowerCase().trim();
  return worldCountries.filter(
    (c) =>
      c.name.toLowerCase().includes(q) ||
      c.code.toLowerCase().includes(q) ||
      c.continent.toLowerCase().includes(q)
  );
}
